// End-to-end test: auth. Run all with `npm test`. Uses an in-memory database (tests/fakedb.js)
// and stubbed email/storage, so it never touches Supabase or sends real email.
const ROOT = require('path').join(__dirname, '..');
process.env.PORT = '3561'; process.env.BASE_URL = 'http://localhost:3561';
process.env.SUPABASE_URL = 'http://127.0.0.1:59999'; process.env.SUPABASE_SERVICE_KEY = 'x';
process.env.RESEND_API_KEY = 'x'; process.env.ADMIN_EMAIL = 'gil@autowerkeit.com'; process.env.ADMIN_PASSWORD = 'Bootstrap-Pass-2026'; process.env.ADMIN_NAME = 'Gil Magezah';
process.env.APP_SECRET = 'a'.repeat(64); process.env.NODE_ENV = 'production';
const assert = require('assert');
const dbm = require(ROOT + '/lib/db');
const T = require('./fakedb.js')(dbm);
const realFetch = global.fetch; const emails = [];
global.fetch = async (u, o) => (String(u).includes('api.resend.com') ? (emails.push(JSON.parse(o.body)), { ok: true, json: async () => ({}) }) : realFetch(u, o));
require(ROOT + '/server.js');
const B = 'http://localhost:3561';
const post = (p, body, h = {}) => realFetch(B + p, { method: 'POST', headers: { 'Content-Type': 'application/json', ...h }, body: JSON.stringify(body), redirect: 'manual' });
const codeFrom = (m) => (m.subject.match(/code: ([A-Z]{6})$/) || [])[1];
(async () => {
  await new Promise((r) => setTimeout(r, 400));
  let r = await post('/api/auth/login', { email: 'gil@autowerkeit.com', password: 'wrong-password' });
  const wrongPw = await r.json();
  assert.strictEqual(r.status, 401);
  assert.strictEqual(T.admin_users.length, 1);
  assert(T.admin_users[0].password_hash.startsWith('scrypt$') && !JSON.stringify(T.admin_users).includes('Bootstrap-Pass'));
  r = await post('/api/auth/login', { email: 'nobody@example.com', password: 'whatever' });
  assert.strictEqual(wrongPw.error, (await r.json()).error);
  assert.strictEqual(emails.length, 0);
  console.log('1. owner created on first sign-in (scrypt-hashed); wrong password = unknown email; no code sent ✓');
  r = await post('/api/auth/login', { email: 'GIL@autowerkeit.com ', password: 'Bootstrap-Pass-2026' });
  const step = await r.json();
  assert(r.status === 200 && step.step === 'code' && step.sentTo === 'g**@autowerkeit.com');
  const code = codeFrom(emails[0]);
  assert(code && emails[0].html.split('border:2px solid #2F4A3B').length - 1 === 6);
  assert(!JSON.stringify(T.auth_codes).includes(code));
  console.log(`2. right password -> 6-letter code in 6 boxes (${code}); stored only as a hash ✓`);
  for (let i = 1; i <= 4; i++) assert.strictEqual((await post('/api/auth/verify', { email: 'gil@autowerkeit.com', code: 'AAAAAA' })).status, 401);
  const fifth = await (await post('/api/auth/verify', { email: 'gil@autowerkeit.com', code: 'AAAAAA' })).json();
  assert.strictEqual((await post('/api/auth/verify', { email: 'gil@autowerkeit.com', code })).status, 401);
  console.log(`3. 5 wrong codes -> "${fifth.error}"; the correct code no longer works ✓`);
  await post('/api/auth/login', { email: 'gil@autowerkeit.com', password: 'Bootstrap-Pass-2026' });
  const code2 = codeFrom(emails.at(-1));
  r = await post('/api/auth/verify', { email: 'gil@autowerkeit.com', code: code2.toLowerCase().split('').join(' '), next: '//evil.com/phish' });
  const ok = await r.json(); const cookie = r.headers.get('set-cookie');
  assert(r.status === 200 && ok.next === '/admin');
  assert(/aw_admin=[^;]{40,}/.test(cookie) && /HttpOnly/.test(cookie) && /SameSite=Strict/.test(cookie));
  const token = cookie.match(/aw_admin=([^;]+)/)[1];
  assert(!JSON.stringify(T.admin_sessions).includes(token));
  assert.strictEqual((await post('/api/auth/verify', { email: 'gil@autowerkeit.com', code: code2 })).status, 401);
  console.log('4. correct code (case/spaces forgiven) -> HttpOnly + SameSite=Strict cookie, token hashed; "next=//evil.com" ignored; single-use ✓');
  const C = { Cookie: `aw_admin=${token}` };
  assert.strictEqual((await (await realFetch(B + '/api/auth/me', { headers: C })).json()).name, 'Gil Magezah');
  assert.strictEqual((await realFetch(B + '/api/admin/workspaces', { redirect: 'manual' })).status, 401);
  r = await realFetch(B + '/admin/earnings', { redirect: 'manual' });
  assert(r.status === 302 && r.headers.get('location') === '/admin/login?next=%2Fadmin%2Fearnings');
  assert.strictEqual((await realFetch(B + '/admin/earnings', { headers: C, redirect: 'manual' })).status, 200);
  console.log('5. signed in -> admin works; signed out -> APIs 401, pages redirect to sign-in and back ✓');
  for (const f of ['/admin.html', '/earnings.html', '/workspace.html', '/EARNINGS.HTML']) assert.strictEqual((await realFetch(B + f)).status, 404, f);
  console.log('6. admin page files no longer load directly ✓');
  r = await realFetch(B + '/api/admin/team', { method: 'POST', headers: { ...C, 'Content-Type': 'application/json', Origin: 'https://evil.example' }, body: '{}' });
  assert.strictEqual(r.status, 403);
  console.log('7. a request from another website carrying the cookie is blocked (403) ✓');
  const h = Object.fromEntries((await realFetch(B + '/')).headers);
  assert(h['content-security-policy'].includes("script-src 'self'") && h['x-frame-options'] === 'DENY' && h['x-content-type-options'] === 'nosniff' && !h['x-powered-by']);
  console.log('8. security headers: strict CSP, no framing, nosniff, server fingerprint hidden ✓');
  // Signed-in time: the session clock starts at sign-in (survives a refresh), and all time adds every session up
  assert.strictEqual((await realFetch(B + '/api/auth/time')).status, 401);
  const gilId = T.admin_users[0].id;
  const mine = T.admin_sessions.find((x) => x.admin_id === gilId && !x.revoked_at);
  const me2 = await (await realFetch(B + '/api/auth/me', { headers: C })).json();
  assert.strictEqual(me2.sessionStartedAt, mine.created_at);
  const H = 3600e3; const M = 60e3; const base = Date.now() - 10 * 24 * H;
  const at = (ms) => new Date(base + ms).toISOString();
  const old = (f) => T.admin_sessions.push({ id: require('crypto').randomUUID(), token_hash: require('crypto').randomUUID(), admin_id: gilId, revoked_at: null, ...f });
  old({ created_at: at(0), last_seen_at: at(59 * M), revoked_at: at(60 * M), expires_at: at(12 * H) });           // signed out after 1h
  old({ created_at: at(30 * M), last_seen_at: at(90 * M), expires_at: at(12 * H) });                             // another browser, overlapping: union is 90 min
  old({ created_at: at(24 * H), last_seen_at: at(26 * H), revoked_at: at(72 * H), expires_at: at(36 * H) });     // timed out, revoked days later: 2h
  old({ created_at: at(48 * H), last_seen_at: at(70 * H), expires_at: at(60 * H) });                             // can't run past its 12h expiry
  old({ created_at: at(0), last_seen_at: at(5 * H), expires_at: at(12 * H), admin_id: T.admin_users[1] ? T.admin_users[1].id : 'someone-else' }); // not Gil's
  const tm = await (await realFetch(B + '/api/auth/time', { headers: C })).json();
  const expected = 90 * M + 2 * H + 12 * H;
  assert(tm.allTimeMs >= expected && tm.allTimeMs < expected + 60e3, `all time ${tm.allTimeMs}`);
  assert(tm.sessions === 5 && tm.since === at(0) && tm.sessionStartedAt === mine.created_at);
  const { signedInMs } = require(ROOT + '/lib/auth');
  assert.strictEqual(signedInMs([{ id: 'x', created_at: at(0), last_seen_at: 'nonsense', revoked_at: null, expires_at: null }], 'y', base + H).totalMs, 0);
  assert.strictEqual(signedInMs([{ id: 'x', created_at: at(0), last_seen_at: at(0), expires_at: at(12 * H) }], 'x', base + H).totalMs, H);
  console.log('8b. session clock starts at sign-in (refresh-proof); all-time = union of sessions, idle-after-timeout and past-expiry excluded ✓');
  const J = { ...C, 'Content-Type': 'application/json' };
  assert.strictEqual((await realFetch(B + '/api/admin/team', { method: 'POST', headers: J, body: JSON.stringify({ name: 'Tino', email: 'tino@autowerkeit.com', password: 'weak' }) })).status, 400);
  const tino = await (await realFetch(B + '/api/admin/team', { method: 'POST', headers: J, body: JSON.stringify({ name: 'Tino', email: 'tino@autowerkeit.com', password: 'Colleague-Pass-99' }) })).json();
  await post('/api/auth/login', { email: 'tino@autowerkeit.com', password: 'Colleague-Pass-99' });
  r = await post('/api/auth/verify', { email: 'tino@autowerkeit.com', code: codeFrom(emails.at(-1)) });
  const TC = { Cookie: `aw_admin=${r.headers.get('set-cookie').match(/aw_admin=([^;]+)/)[1]}` };
  assert.strictEqual((await realFetch(B + '/api/admin/team', { method: 'POST', headers: { ...TC, 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'X', email: 'x@x.com', password: 'Colleague-Pass-99' }) })).status, 403);
  await realFetch(B + `/api/admin/team/${tino.id}`, { method: 'PATCH', headers: J, body: JSON.stringify({ active: false }) });
  assert.strictEqual((await realFetch(B + '/api/auth/me', { headers: TC })).status, 401);
  console.log('9. weak passwords refused; only the owner manages the team; deactivating signs them out instantly ✓');
  await realFetch(B + '/api/auth/logout', { method: 'POST', headers: C });
  assert.strictEqual((await realFetch(B + '/api/auth/me', { headers: C })).status, 401);
  console.log('10. sign out revokes the session server-side: a copied cookie is useless ✓');
  require(ROOT + '/lib/security').resetRateLimits();
  let last; for (let i = 0; i < 6; i++) last = await post('/api/auth/login', { email: 'gil@autowerkeit.com', password: `guess${i}` });
  assert.strictEqual(last.status, 429);
  console.log(`11. password guessing: 6th try in 15 minutes -> 429 "${(await last.json()).error}" ✓`);
  require(ROOT + '/lib/security').resetRateLimits();
  const saved = dbm.countAdmins;
  dbm.countAdmins = async () => { throw new Error("DB query failed: Could not find the table 'public.admin_users' in the schema cache"); };
  r = await post('/api/auth/login', { email: 'gil@autowerkeit.com', password: 'x' });
  console.log(`12. before schema_secure.sql is run -> ${r.status}: "${(await r.json()).error}" ✓`);
  dbm.countAdmins = saved;
  process.exit(0);
})().catch((e) => { console.error('FAIL:', e.message); process.exit(1); });
